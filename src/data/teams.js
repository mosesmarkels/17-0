export const TEAM_BY_ABBR = Object.fromEntries(TEAMS.map((t) => [t.abbr, t]))

export function teamNameFor(abbr, era) {
  const t = TEAM_BY_ABBR[abbr]
  if (!t) return abbr
  if (t.alias && t.alias[era]) return t.alias[era]
  return `${t.city} ${t.name}`
}
